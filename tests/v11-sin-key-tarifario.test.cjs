'use strict';
const assert=require('node:assert/strict');
const fs=require('fs');
const path=require('path');
const base=path.resolve(__dirname,'..');
const src=name=>fs.readFileSync(path.join(base,name),'utf8');
const app=src('app.js'),html=src('index.html'),toll=src('tolls.js'),report=src('executive-report.js');
const {quote,detailedBreakdown,render}=require('../imt-cost-model');
assert(!app.includes("fetch('/.netlify/functions/inegi-sakbe'"),'ruteo ya no consulta servicio con key');
assert(!fs.existsSync(path.join(base,'netlify/functions/inegi-sakbe.js')),'proxy SAKBÉ no debe incluirse');
assert(app.includes('router.project-osrm.org')&&app.includes('NO apta para despacho'),'rutas abiertas identificadas como no certificadas');
assert(html.includes('gcTierFields')&&render(quote({km:60,loadTons:9,type:'Rabón',dieselPrice:26.68})).includes('Referencias tarifarias'),'Referencias tarifarias C/C’/B deben conservarse aparte del desglose');
assert(toll.includes('overpass-api.de')&&toll.includes('casetas-ruta'),'Overpass abierto funciona sin Netlify');
assert(toll.includes('partial'),'Peajes nunca marcados exhaustivos');
const q=quote({km:90,loadTons:28,type:'Tráiler',dieselPrice:26.68,dieselPriceIncludesIVA:true,tollsOneWay:464,tollsPriceIncludesIVA:true,operatorMode:'variable',operatorPerKm:3});
const d=detailedBreakdown(q);
assert.equal(q.audit.dieselPrice,23);
assert.equal(q.variable.tolls,800);
assert(Math.abs([...d.fixed,...d.variable].reduce((s,r)=>s+r.amount,0)-q.cost)<1e-6);
assert(Math.abs(d.fixedPercent+d.variablePercent-1)<1e-9);
assert(d.variable.find(x=>x.label==='Operador variable').amount>0);
assert(d.fixed.find(x=>x.label==='Operador – sueldo fijo').amount===0);
for(const key of ['Diésel','Mantenimiento','Llantas','Operador variable','Vehículo / depreciación','Mano de obra de mantenimiento','Gastos administrativos','Seguros']) assert(render(q).includes(key),'Falta componente '+key);
assert(report.includes('Cierre de la tarifa')&&report.includes('Referencias tarifarias comerciales (escenarios)'));
console.log('PASS V11: sin key, diesel y peajes netos, presupuesto componentes MXN/% y no doble operador.');
