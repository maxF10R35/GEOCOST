'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {quote,defs,detailedBreakdown,render}=require('../imt-cost-model.js');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const app=fs.readFileSync(path.join(root,'app.js'),'utf8');
const report=fs.readFileSync(path.join(root,'executive-report.js'),'utf8');
assert(!html.includes('id="p-demanda-visual"'),'El bloque demanda/carga sigue visible');
assert(!html.includes('Lote por viaje (Tn)'),'Se muestra la captura manual de lote');
assert(!html.includes('Número de viajes</label>'),'Se muestra la captura de número de viajes');
assert(html.includes('id="draw"')&&html.includes('id="openCostSettings"'),'Acciones de cotización deben permanecer');
assert(html.includes('type="hidden" id="ton"'),'El motor conserva el lote óptimo oculto');
assert(html.includes('type="hidden" id="numeroViajes"'),'Se conserva el valor operativo 1 viaje');
assert(app.includes("presentation==='Granel'?['Tráiler','Full'].includes(u.name)"),'Granel debe permitir Tráiler y Full');
assert(report.includes("presentation==='Granel'?['Tráiler','Full'].includes(u.name)"),'El reporte debe permitir Tráiler y Full');
for (const type of ['Tráiler','Full']) {
 const q=quote({type,cargoType:'granel',km:87,loadTons:defs[type].cap,travelHours:2.2,dieselPrice:26.5,tollsOneWay:220});
 assert(q.tariff>0&&q.loadTons===defs[type].cap&&q.cargoType==='granel');
 const d=detailedBreakdown(q);
 const total=d.fixed.reduce((a,x)=>a+x.amount,0)+d.variable.reduce((a,x)=>a+x.amount,0);
 assert(Math.abs(total-q.cost)<1e-7,'Detalle debe reconciliar al costo total');
 assert(Math.abs(d.fixedPercent+d.variablePercent-1)<1e-9);
 const markup=render(q);
 assert(markup.includes('Costos fijos')&&markup.includes('Costos variables'));
 assert(markup.includes('gc-cost-money')&&markup.includes('gc-cost-percent'));
 assert(!markup.includes('Desglose detallado de costos')&&!markup.includes('Participación del costo por componente'),'No duplicar desglose');
 assert(!markup.includes('Fluctuación')&&!markup.includes('Impacto'));
}
const variable=quote({type:'Tráiler',cargoType:'granel',km:120,loadTons:28,travelHours:3,dieselPrice:26.5,operatorMode:'variable',operatorPerKm:3});
const list=detailedBreakdown(variable);
const operator=list.variable.find(r=>r.label==='Operador variable');
assert(operator&&Math.abs(operator.amount-720)<1e-9,'Operador variable se identifica correctamente');
assert(!list.fixed.some(r=>r.amount>0&&r.label.includes('Operador')),'El operador variable no se duplica como fijo');
const total=[...list.fixed,...list.variable].reduce((a,r)=>a+r.amount,0);
assert(Math.abs(total-variable.cost)<1e-7,'La suma sigue cuadrando cuando el operador es variable');
assert(report.includes('budgetList('),'Reporte ejecutivo comparte el desglose detallado');
console.log('PASS V7: demanda removida, Tráiler y Full granel, listas separadas en MXN/% y reconciliación sin doble operador.');
