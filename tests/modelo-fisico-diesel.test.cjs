'use strict';
const assert=require('node:assert/strict');
const physics=require('../road-physics-core.js');
const fuel=require('../fuel-core.js');
const {quote,carrierProfiles}=require('../imt-cost-model.js');
const base={type:'Rabón',km:100,loadTons:9,year:2022,travelHours:2,dieselPrice:26,utility:.08,elevationAvailable:true,ascent:100,descent:100,rows:[{id:'pavimento_sin',km:100}]};
const road=physics.aggregate([{km:35,road:'urbano',grade:1},{km:40,road:'pavimento',grade:4.2},{km:25,road:'terraceria',grade:-5.1}],100);
assert.equal(Math.round(road.classifiedKm),100);assert.equal(road.unknownKm,0);
assert.equal(road.rows.find(x=>x.id==='pavimento_con').km,40);
assert.equal(road.rows.find(x=>x.id==='terraceria_con').km,25);
const partial=physics.aggregate([{km:45,road:null,grade:null},{km:55,road:'pavimento',grade:0}],100);assert.equal(partial.unknownKm,45);
const f=fuel.weighted({routeKm:100,byState:{mexico:35,puebla:65}},{mexico:25,puebla:27},26.99);
assert(Math.abs(f.price-26.3)<1e-8,'precio medio estados ponderado por km');
const incomplete=fuel.weighted({routeKm:100,byState:{mexico:30,puebla:60}},{mexico:25},26.99);
assert.equal(incomplete.price,25,'no usar respaldo nacional por km sin precio estatal');
assert(Math.abs(incomplete.coverage-.3)<.001,'transparencia cobertura parcial');
assert(Number.isNaN(fuel.weighted({routeKm:100,byState:{}},{},26.99).price),'sin estados no se produce tarifa calculable');
const p=quote({...base,dieselPrice:f.price});assert.equal(p.audit.dieselPrice,26.3);assert(Math.abs(p.variable.diesel-p.dieselLitres*26.3)<1e-8);
const pNet=quote({...base,dieselPrice:f.price,dieselPriceIncludesIVA:true});
assert(Math.abs(pNet.audit.dieselPrice-f.price/1.16)<1e-9,'descontar 16% IVA al diésel reportado');
assert(Math.abs(pNet.variable.diesel-pNet.dieselLitres*f.price/1.16)<1e-8,'costo de diésel neto = litros × precio sin IVA');
assert.equal(pNet.audit.dieselIncludesIVA,true,'fuente marcada con IVA');
assert(Math.abs(pNet.tariff-p.tariff)>1,'descuento afecta también tarifa');
const pAlreadyNet=quote({...base,dieselPrice:f.price/1.16,dieselPriceIncludesIVA:false});
assert(Math.abs(pAlreadyNet.variable.diesel-pNet.variable.diesel)<1e-8,'no descontar doble IVA cuando precio ya es neto');
const higher=quote({...base,dieselPrice:28});assert(higher.tariff>p.tariff,'diésel se refleja en tarifa total');
const hills=quote({...base,ascent:1100,descent:560});assert(hills.variable.diesel>p.variable.diesel,'mayor ascenso cuesta más diésel');assert(hills.variable.maintenance>p.variable.maintenance,'mayor gradiente cuesta más mantenimiento');
const gravel=quote({...base,rows:[{id:'terraceria_sin',km:100}]});assert(gravel.variable.maintenance>p.variable.maintenance,'superficie afecta mantenimiento');
const unsupported=quote({...base,legacyEffortPct:100,ira:5});assert.equal(unsupported.tariff,quote(base).tariff,'no usa índices antiguos GeoRisk');
const chico=carrierProfiles.chico,grande=carrierProfiles.grande;
const small=quote({...base,carrierAdminFactor:chico.admin,carrierPatioFactor:chico.patio,carrierUtilizationFactor:chico.utilization});
const big=quote({...base,carrierAdminFactor:grande.admin,carrierPatioFactor:grande.patio,carrierUtilizationFactor:grande.utilization});
assert(big.monthly.admin>small.monthly.admin&&big.fixedAllocation>small.fixedAllocation,'mayor infraestructura reflejada en CF');
assert.throws(()=>quote({...base,dieselPrice:null}),/Precio estatal/);
console.log('PASS GC-FIS2: clases viales, omisiones, estados ponderados, sin $26.99 fijo, relieve, CF por flotilla, sin IRA.');
