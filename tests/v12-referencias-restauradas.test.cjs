const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const model=require('../imt-cost-model');
const root=path.resolve(__dirname,'..');
const source=x=>fs.readFileSync(path.join(root,x),'utf8');
const html=source('index.html'),settings=source('gc-settings-clean.js'),report=source('executive-report.js');
assert(html.includes('id="gcTierFields"'),'editable scenario controls visible in settings');
assert(settings.includes('setUpTiers();'),'tier control initialized');
const q=model.quote({type:'Rabón',km:60,loadTons:9,dieselPrice:26.68,tollsOneWay:116,dieselPriceIncludesIVA:true,tollsPriceIncludesIVA:true,tierPremiums:{CP:5,B:10,BP:16,SPOT:22}});
assert.deepEqual(q.refTiers.map(t=>t.id),['C','CP','B','BP','SPOT']);
assert(Math.abs(q.refTiers[0].amount-q.tariff)<1e-7,'C is baseline');
assert(Math.abs(q.refTiers[1].amount-q.tariff*1.05)<1e-7,'editable C prime');
assert(Math.abs(q.refTiers[4].amount-q.tariff*1.22)<1e-7,'editable B SPOT');
const view=model.render(q);
assert(['C´','B+','B SPOT','Costos variables','Costos fijos','Referencias tarifarias'].every(x=>view.includes(x)),'all three sections visible');
assert(!view.includes('Fluctuación')&&!view.includes('Impacto'),'no excluded indices');
assert(report.includes('main.refTiers.map'),'report uses same model');
assert(!html.includes('INEGI_SAKBE_TOKEN'),'no key requirement');
assert.equal(q.audit.dieselPrice,23);
assert.equal(q.variable.tolls,200);
console.log('PASS V12: restored editable tariff tiers, preserved separate fixed/variable, VAT-free and no API token.');
