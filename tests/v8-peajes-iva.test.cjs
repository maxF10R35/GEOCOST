const assert=require('node:assert/strict');
const {matchTolls,vehicleClass,nearRouteKm,norm,takeAlongRoute}=require('../toll-core');
const {quote}=require('../imt-cost-model');
const route=[[19.5,-99.25],[19.51,-99.24],[19.52,-99.23],[19.53,-99.22]];
const price=[{id:'A',name:'Paseo Alto',section:'X-Y',rates:{C2:116,C5:290},effective:'2026-04-13'}];
const toll=[{id:'osm:1',name:'Caseta Paseo Alto',lat:19.515,lon:-99.235},{id:'osm:2',name:'Caseta Paseo Alto',lat:19.5151,lon:-99.2351},{id:'osm:4',name:'Sin tarifa',lat:19.52,lon:-99.23}];
const result=matchTolls(toll,price,'C2',route);
assert.equal(result.identified.length,1,'two lanes are deduplicated');
assert.equal(result.oneWayGross,116);
assert.equal(result.unpriced.length,1,'unpriced gate is explicit');
assert.equal(result.complete,false,'cannot claim exhaustive toll coverage');
assert.equal(vehicleClass('Tráiler'),'C5');assert.equal(vehicleClass('Full'),'C9');
const far=matchTolls([{name:'Paseo Alto',lat:19.8,lon:-99.3}],price,'C2',route);
assert.equal(far.oneWayGross,0,'unrelated toll must not be assigned');
const ambiguous=matchTolls([{name:'Caseta Paseo Alto',lat:19.515,lon:-99.235}],price.concat({id:'B',name:'Paseo Alto',section:'I2',rates:{C2:75}}),'C2',route);
assert.equal(ambiguous.oneWayGross,0,'different section tariffs may not be fabricated');
assert.equal(ambiguous.unpriced.length,1);
assert.equal(norm('Caseta PASEO ÁLTO'),norm('Paseo Alto'));
assert(takeAlongRoute(route,100).length>=2);
const base={type:'Rabón',year:2022,km:52,travelHours:1.2,loadTons:9,dieselPrice:26.68,elevationAvailable:false};
const gross=quote({...base,tollsOneWay:116,dieselPriceIncludesIVA:false,tollsPriceIncludesIVA:false});
const net=quote({...base,tollsOneWay:116,dieselPriceIncludesIVA:true,tollsPriceIncludesIVA:true});
assert(Math.abs(net.audit.dieselPrice-23)<1e-8);
assert(Math.abs(net.variable.tolls-200)<1e-8);
assert(Math.abs(gross.variable.tolls-232)<1e-8);
assert(Math.abs(gross.variable.diesel/net.dieselLitres-26.68)<1e-8);
assert.equal(net.audit.tollsOneWayNet,100);
assert(net.tariff<gross.tariff,'tax exclusion reduces cost');
const modified=quote({...base,tollsOneWay:116,dieselPriceIncludesIVA:true,tollsPriceIncludesIVA:true,tollStatus:'pending'});
assert(modified.warnings.some(w=>/Casetas: detección/i.test(w)),'pending toll must be flagged');
const html=require('node:fs').readFileSync(require('node:path').join(__dirname,'../index.html'),'utf8');
assert(html.includes('toll-core.js'));
assert(html.includes('id="tollItems"'));
assert(html.indexOf('id="tollItems"')<html.indexOf('gc-toll-manual'), 'automated readout must remain visible without opening manual entry');
console.log('PASS V8: VAT diesel and tolls, cartographic matching, duplicate lanes, ambiguous sections, warning, UI.');
